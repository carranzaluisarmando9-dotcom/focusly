import AxeBuilder from '@axe-core/playwright'
test('WCAG automated checks in light/dark and task dialogs',async({page})=>{
 await page.goto('/')
 for(const theme of ['Modo claro','Modo oscuro']){
  await page.getByRole('radio',{name:theme,exact:true}).check()
  const results=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()
  expect(results.violations.map(v=>({id:v.id,help:v.help,nodes:v.nodes.map(n=>n.target)}))).toEqual([])
 }
 await page.getByRole('button',{name:'Nueva tarea',exact:true}).first().click()
 const dialog=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()
 expect(dialog.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([])
})

