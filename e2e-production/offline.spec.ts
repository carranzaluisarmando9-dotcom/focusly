import { test,expect } from '@playwright/test'
test('production PWA shell works after an offline reload',async({page,context})=>{
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Encuentra tu ritmo.'})).toBeVisible()
 const manifestURL=await page.locator('link[rel=manifest]').getAttribute('href')
 const response=await page.request.get(manifestURL!)
 expect(response.status()).toBe(200)
 const manifest=await response.json()
 expect(manifest.display).toBe('standalone')
 expect(manifest.lang).toBe('es-PE')
 for(const icon of manifest.icons){expect((await page.request.get(icon.src)).status()).toBe(200)}
 await page.evaluate(()=>navigator.serviceWorker.ready)
 await page.reload()
 await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true)
 await context.setOffline(true)
 await page.reload()
 await expect(page.getByRole('heading',{name:'Encuentra tu ritmo.'})).toBeVisible()
 await page.getByRole('button',{name:'Nueva tarea',exact:true}).first().click()
 await page.getByLabel('Título',{exact:false}).fill('Trabajo sin conexión')
 await page.getByRole('button',{name:'Guardar tarea'}).click()
 await page.reload()
 await expect(page.locator('.task-copy h3',{hasText:'Trabajo sin conexión'})).toBeVisible()
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
 await page.reload()
 await expect(page.getByRole('button',{name:'Pausar',exact:true})).toBeVisible()
 await context.setOffline(false)
})
